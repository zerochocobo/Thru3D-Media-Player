"""Turns Anime4K mpv hook shaders into GLES 3.0 fragment shaders.

Usage: convert.py [--precision mediump|highp|none] <out.h> <name>=<hook.glsl> ...
Each hook file becomes an array of passes: the textures it binds, the texture it saves, whether it
doubles the size, and the fragment source. The layer arithmetic and weights are copied as they are;
only mpv's hook interface (//! headers, NAME_texOff, NAME_tex, NAME_pos, NAME_size, NAME_pt) is
replaced with plain GLES sampling. With --precision none the source keeps a PRECISION_LINE marker for
the benchmark to fill in.

The player's header: python -I tools/anime4k/convert.py native/xr-layer/anime4k_glsl.h \
  restore_s=third_party/anime4k/glsl/Anime4K_Restore_CNN_S.glsl ... (tools/anime4k/Generate-Anime4kGlsl.ps1)
"""
import re
import sys


def passes(path, precision):
    text = open(path, encoding="utf-8").read()
    blocks = re.split(r"(?m)^(?=//!DESC)", text)[1:]
    result = []
    for block in blocks:
        binds, save, doubled, body = [], None, False, []
        for line in block.splitlines():
            if line.startswith("//!BIND"):
                binds.append(line.split()[1])
            elif line.startswith("//!SAVE"):
                save = line.split()[1]
            elif line.startswith("//!WIDTH"):
                doubled = line.rstrip().endswith("2 *")
            elif line.startswith("//!"):
                continue
            else:
                body.append(line)
        source = "\n".join(body).strip()
        # A 3x3 tap at a constant offset: textureOffset keeps the address arithmetic out of the shader.
        source = re.sub(r"(\w+)_texOff\(vec2\(x_off, y_off\)\)", r"textureOffset(\1, v_uv, ivec2(x_off, y_off))", source)
        header = ["#version 300 es", "PRECISION_LINE" if precision == "none" else f"precision {precision} float;",
                  "precision highp sampler2D;", "in highp vec2 v_uv;", "out vec4 frag;"]
        for name in binds:
            header.append(f"uniform sampler2D {name};")
            header.append(f"#define {name}_pos v_uv")
            header.append(f"#define {name}_tex(p) texture({name}, p)")
            header.append(f"#define {name}_size vec2(textureSize({name}, 0))")
            header.append(f"#define {name}_pt (1.0 / {name}_size)")
        fragment = "\n".join(header) + "\n" + source + "\nvoid main() { frag = hook(); }\n"
        result.append((binds, save, doubled, fragment))
    return result


def c_string(text):
    return "\n".join('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"' for line in text.splitlines())


def main():
    arguments = sys.argv[1:]
    precision = "mediump"
    if arguments[0] == "--precision":
        precision = arguments[1]
        arguments = arguments[2:]
    out = ["// Generated by tools/anime4k/convert.py from Anime4K (MIT, Copyright (c) 2019-2021 bloc97,",
           "// third_party/anime4k). Do not edit: change the converter and generate it again.",
           "#pragma once",
           "struct Pass { const char* binds[16]; int bind_count; const char* save; bool doubled; const char* fragment; };",
           "struct Chain { const char* name; const Pass* passes; int count; };"]
    chains = []
    for argument in arguments[1:]:
        name, path = argument.split("=", 1)
        entries = []
        for binds, save, doubled, fragment in passes(path, precision):
            bind_list = ", ".join(f'"{b}"' for b in binds)
            entries.append(f'  {{ {{{bind_list}}}, {len(binds)}, "{save}", {"true" if doubled else "false"},\n{c_string(fragment)} }}')
        out.append(f"static const Pass {name}_passes[] = {{\n" + ",\n".join(entries) + "\n};")
        chains.append(f'{{"{name}", {name}_passes, {len(entries)}}}')
    out.append("static const Chain chains[] = {" + ", ".join(chains) + "};")
    with open(arguments[0], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out) + "\n")


main()
