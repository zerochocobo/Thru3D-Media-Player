def build():
    rows=CHARTS.splitlines()
    assert len(rows)==64 and len(set(rows))==64
    tile=256
    sheet=Image.new("RGB",(tile*8,tile*8))
    for index,row in enumerate(rows):
        name,strokes=row.split("|")
        rng=random.Random(name)
        pic=Image.new("RGB",(tile,tile),(9,14,38))
        ink=ImageDraw.Draw(pic)
        for j in range(260):
            x,y=rng.randrange(tile),rng.randrange(tile)
            value=rng.randrange(32,140)
            ink.point((x,y),fill=(int(value*.72),int(value*.81),value))
        glow=Image.new("RGB",pic.size)
        draw=ImageDraw.Draw(glow)
        for stroke in strokes.split("/"):
            p=[(26+int(s[0])*22,26+int(s[1])*22) for s in stroke.split()]
            draw.line(p,fill=(77,133,204),width=2)
            for x,y in p:
                r=rng.choice([1.7,2,2.6])
                draw.ellipse((x-r,y-r,x+r,y+r),fill=(228,220,174) if rng.random()<.20 else (198,223,255))
        sheet.paste(ImageChops.add(pic,ImageChops.add(glow,glow.filter(ImageFilter.GaussianBlur(3)))),
                    (index%8*tile,index//8*tile))
    target=Path(__file__).resolve().parents[2]/"app/godot/environments/magic_cottage/star-atlas.jpg"
    target.parent.mkdir(parents=True,exist_ok=True)
    sheet.save(target,quality=93,subsampling=0)


if __name__=="__main__":
    build()
